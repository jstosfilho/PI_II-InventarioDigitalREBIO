CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK(role IN ('gestor','editor','leitor'))
);
CREATE TABLE IF NOT EXISTS features (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL CHECK(length(name) BETWEEN 3 AND 120),
 kind TEXT NOT NULL CHECK(kind IN ('trilha','nascente')),
 description TEXT NOT NULL DEFAULT '',
 photo_url TEXT NOT NULL DEFAULT '',
 category TEXT NOT NULL DEFAULT '',
 geometry_file TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL CHECK(status IN ('a_verificar','conservado','atencao')),
 geometry TEXT NOT NULL,
 source TEXT NOT NULL,
 observed_on TEXT NOT NULL,
 created_by BIGINT NOT NULL REFERENCES users(id),
 created_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
 updated_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
 version INTEGER NOT NULL DEFAULT 1,
 archived INTEGER NOT NULL DEFAULT 0 CHECK(archived IN (0,1))
);
CREATE INDEX IF NOT EXISTS features_kind_status ON features(kind,status,archived);
CREATE TABLE IF NOT EXISTS history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 feature_id BIGINT NOT NULL REFERENCES features(id),
 actor_id BIGINT NOT NULL REFERENCES users(id),
 action TEXT NOT NULL,
 snapshot TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
);
CREATE INDEX IF NOT EXISTS history_feature_id ON history(feature_id,id);
